"""Test publisher for the zenoh_flutter viewer.

Publishes five topics to a router on tcp/localhost:7447 so every card type
in the app can be exercised. test/imu, test/cam and test/raw carry protobuf
messages from tools/proto/demo.proto (package zenoh_demo). test/temperature
carries the same Imu sample as test/imu, encoded as the FlatBuffers table from
tools/fbs/demo.fbs (namespace zenoh_demo). The Python bindings
tools/demo_pb2.py and tools/demo_generated.py are generated by
tools/gen_messages.sh.

  test/imu          50 Hz  zenoh_demo.Imu (accel, gyro, temp)       application/protobuf;zenoh_demo.Imu
  test/temperature  50 Hz  the test/imu sample as FlatBuffers       application/flatbuffers;zenoh_demo.Imu
  test/topic        2 Hz   text "hello world <unix seconds>"        text/plain
  test/cam          30 Hz  zenoh_demo.Image, 320x240 JPEG (Pillow)  application/protobuf;zenoh_demo.Image
  test/raw          5 Hz   zenoh_demo.Raw, 256 bytes                application/protobuf;zenoh_demo.Raw

Each protobuf and FlatBuffers message starts with a Header: timestamp_ns
(UNIX time in ns) and seq (a counter per topic, starting at 0). zenoh has no
built-in FlatBuffers encoding, so test/temperature sets the encoding string
`application/flatbuffers;zenoh_demo.Imu` itself; the viewer picks its decoder
from it. test/cam is skipped when Pillow is not installed.

Requires: pip install eclipse-zenoh protobuf flatbuffers pillow
Run:      python3 tools/test_publisher.py     (Ctrl-C to stop)
"""
import io, math, sys, time, zenoh

try:
    import flatbuffers
    import demo_pb2 as pb
    import demo_generated as fb
except Exception as e:  # missing runtime, missing or stale demo_pb2.py / demo_generated.py
    sys.exit(f"test_publisher: cannot import the message bindings ({e}); run `pip install protobuf flatbuffers`, "
             "or regenerate demo_pb2.py and demo_generated.py with `bash tools/gen_messages.sh`")

try:
    from PIL import Image, ImageDraw
except ImportError:
    Image = None

def make_jpeg(n):
    img = Image.new("RGB", (320, 240), (20 + (n * 3) % 200, 60, 120))
    d = ImageDraw.Draw(img)
    d.rectangle([20 + (n * 5) % 250, 80, 70 + (n * 5) % 250, 160], fill=(240, 200, 40))
    d.text((10, 10), f"frame {n}", fill=(255, 255, 255))
    buf = io.BytesIO(); img.save(buf, format="JPEG", quality=70); return buf.getvalue()

def proto_encoding(msg_type):
    # `application/protobuf;zenoh_demo.<Message>`: the viewer picks its decoder by this schema.
    return zenoh.Encoding.APPLICATION_PROTOBUF.with_schema(msg_type.DESCRIPTOR.full_name)

seqs = {}
def next_seq(topic):
    """Returns the next seq for topic: 0, 1, 2, ..."""
    seq = seqs.get(topic, 0)
    seqs[topic] = seq + 1
    return seq

def stamp(msg, topic, ts=None):
    """Fills msg.header with ts (default: now) and the next seq for topic, returns msg."""
    msg.header.timestamp_ns = time.time_ns() if ts is None else ts
    msg.header.seq = next_seq(topic)
    return msg

def imu_flatbuffer(ts, seq, accel, gyro, temp):
    """Serializes a FlatBuffers zenoh_demo.Imu. Structs are stored inline, so they are built inside the Add calls."""
    b = flatbuffers.Builder(128)
    fb.ImuStart(b)
    fb.ImuAddHeader(b, fb.CreateHeader(b, ts, seq))
    fb.ImuAddAccel(b, fb.CreateVector3(b, *accel))
    fb.ImuAddGyro(b, fb.CreateVector3(b, *gyro))
    fb.ImuAddTemp(b, temp)
    b.Finish(fb.ImuEnd(b))
    return bytes(b.Output())

conf = zenoh.Config()
conf.insert_json5("connect/endpoints", '["tcp/localhost:7447"]')
conf.insert_json5("mode", '"client"')
s = zenoh.open(conf)
imu = s.declare_publisher("test/imu", encoding=proto_encoding(pb.Imu))
tmp = s.declare_publisher("test/temperature", encoding=zenoh.Encoding("application/flatbuffers;zenoh_demo.Imu"))
txt = s.declare_publisher("test/topic", encoding=zenoh.Encoding.TEXT_PLAIN)
cam = s.declare_publisher("test/cam", encoding=proto_encoding(pb.Image))
raw = s.declare_publisher("test/raw", encoding=proto_encoding(pb.Raw))
t0 = time.monotonic()

def put_imu():
    # One sample, published twice: protobuf on test/imu and FlatBuffers on test/temperature.
    t, ts = time.monotonic() - t0, time.time_ns()
    accel, gyro, temp = (round(math.sin(t), 4), round(math.cos(t), 4), 9.806), (0.0007, 0.0012, -0.0003), 36.4
    m = stamp(pb.Imu(temp=temp), "test/imu", ts)
    m.accel.x, m.accel.y, m.accel.z = accel
    m.gyro.x, m.gyro.y, m.gyro.z = gyro
    imu.put(m.SerializeToString())
    tmp.put(imu_flatbuffer(ts, next_seq("test/temperature"), accel, gyro, temp))

def put_text():
    txt.put(f"hello world {int(time.time())}")

def put_cam():
    m = stamp(pb.Image(width=320, height=240, format="jpeg"), "test/cam")
    m.data = make_jpeg(m.header.seq)
    cam.put(m.SerializeToString())

def put_raw():
    m = stamp(pb.Raw(), "test/raw")
    m.data = bytes([(m.header.seq + k) % 256 for k in range(256)])
    raw.put(m.SerializeToString())

# [next due (monotonic s), period s, action]. The loop sleeps until the earliest
# due entry, runs it and moves its due time on by one period from the old due
# time, so slow ticks do not lower the average rate.
schedule = [[t0, 1 / 50, put_imu], [t0, 1 / 2, put_text], [t0, 1 / 5, put_raw]]
if Image: schedule.append([t0, 1 / 30, put_cam])
print("publishing on test/imu (50 Hz zenoh_demo.Imu), test/temperature (50 Hz FlatBuffers zenoh_demo.Imu), "
      "test/topic (2 Hz text), " + ("test/cam (30 Hz zenoh_demo.Image), " if Image else "")
      + "test/raw (5 Hz zenoh_demo.Raw)" + ("" if Image else "; test/cam is off, `pip install pillow` to enable it"), flush=True)
try:
    while True:
        entry = min(schedule, key=lambda e: e[0])
        delay = entry[0] - time.monotonic()
        if delay > 0: time.sleep(delay)
        entry[2]()
        entry[0] += entry[1]
        # After a long stall (suspend, debugger) resync instead of publishing a burst to catch up.
        if time.monotonic() - entry[0] > 1.0: entry[0] = time.monotonic()
except KeyboardInterrupt:
    pass
finally:
    s.close()
